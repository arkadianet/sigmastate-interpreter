const OUT_DIR: &str = "../core/jvm/src/test/resources/stark-kats";

/// Private const in risc0-zkp (1.2.6 src/lib.rs:64 == 3.0.4 src/lib.rs:54);
/// hardcoded with citation, same as circuit_params.tsv.
const FRI_MIN_DEGREE: usize = 256;

const EXT_SIZE: usize = 4;

/// Deterministic 32-bit LCG (Numerical Recipes constants) — same generator
/// as merkle_iop_kat.rs, different seeds.
struct Lcg(u64);
impl Lcg {
    fn next_u32(&mut self) -> u64 {
        self.0 = self
            .0
            .wrapping_mul(6364136223846793005)
            .wrapping_add(1442695040888963407);
        self.0 >> 32
    }
    fn next_fe(&mut self) -> u32 {
        (self.next_u32() % P as u64) as u32
    }
}

fn join_u32(words: &[u32]) -> String {
    words
        .iter()
        .map(|w| w.to_string())
        .collect::<Vec<_>>()
        .join(",")
}

fn canon_ext(e: &BabyBearExtElem) -> [u32; 4] {
    let s = e.subelems();
    [
        u32::from(s[0]),
        u32::from(s[1]),
        u32::from(s[2]),
        u32::from(s[3]),
    ]
}

// ---------------------------------------------------------------------------
// Null circuit: fri_verify only touches the hash suite + poly_eval, but
// Verifier's impl block requires a CircuitCoreDef — satisfy it with an
// inert circuit (never evaluated by the FRI path).
// ---------------------------------------------------------------------------

struct NullCircuit;

static NULL_TAPS: TapSet<'static> = TapSet {
    taps: &[],
    combo_taps: &[],
    combo_begin: &[],
    group_begin: &[0, 0, 0, 0],
    combos_count: 0,
    reg_count: 0,
    tot_combo_backs: 0,
    group_names: &["accum", "code", "data"],
};

impl CircuitInfo for NullCircuit {
    const CIRCUIT_INFO: ProtocolInfo = ProtocolInfo(*b"FRI_KAT_NULL____");
    const OUTPUT_SIZE: usize = 0;
    const MIX_SIZE: usize = 0;
}

impl TapsProvider for NullCircuit {
    fn get_taps(&self) -> &'static TapSet<'static> {
        &NULL_TAPS
    }
}

impl PolyExt<BabyBear> for NullCircuit {
    fn poly_ext(
        &self,
        _mix: &BabyBearExtElem,
        _u: &[BabyBearExtElem],
        _args: &[&[BabyBearElem]],
    ) -> MixState<BabyBearExtElem> {
        MixState {
            tot: BabyBearExtElem::ZERO,
            mul: BabyBearExtElem::ZERO,
        }
    }
}

impl CircuitCoreDef<BabyBear> for NullCircuit {}

// ---------------------------------------------------------------------------
// Case generation
// ---------------------------------------------------------------------------

struct FriCase {
    degree: usize,
    initial_commit: [u32; 8],
    proof: Vec<u32>,
    /// qck[q][r] = (pos, canonical goal) before round r; r == rounds is the
    /// final-poly comparison state.
    qck: Vec<Vec<(usize, [u32; 4])>>,
    /// Word offset of the first final-polynomial word in `proof`.
    final_off: usize,
}

fn poly_eval(coeffs: &[BabyBearExtElem], x: BabyBearExtElem) -> BabyBearExtElem {
    let mut mul_x = BabyBearExtElem::ONE;
    let mut tot = BabyBearExtElem::ZERO;
    for c in coeffs {
        tot += *c * mul_x;
        mul_x *= x;
    }
    tot
}

/// Assemble the ext element at evaluation index `pos` of a plane-major
/// evaluation buffer (`EXT_SIZE` stacked planes of `domain` base elems) —
/// the layout `batch_expand_into_evaluate_ntt` produces and
/// `MerkleTreeProver` commits (rows = domain/16, cols = 64, column-major:
/// leaf row r, col j*16+i = plane j, eval index i*rows + r).
fn eval_at(planes: &[BabyBearElem], domain: usize, pos: usize) -> [u32; 4] {
    let mut out = [0u32; 4];
    for (j, o) in out.iter_mut().enumerate() {
        *o = u32::from(planes[j * domain + pos]);
    }
    out
}

fn gen_case(name: &'static str, degree: usize, seed: u64) -> FriCase {
    assert!(degree.is_power_of_two());
    let suite = Poseidon2HashSuite::new_suite();
    let hal = CpuHal::new(Poseidon2HashSuite::new_suite());
    let mut lcg = Lcg(seed);

    // Coefficients: EXT_SIZE plane-major base polynomials of length
    // `degree` (the internal layout fri_prove folds).
    let coeffs_vec: Vec<BabyBearElem> = (0..EXT_SIZE * degree)
        .map(|_| BabyBearElem::new(lcg.next_fe()))
        .collect();
    // A deterministic transcript prefix: FRI never starts on a fresh rng in
    // the real protocol, so seed the duplex sponge with one commit.
    let init_elems: Vec<BabyBearElem> =
        (0..9).map(|_| BabyBearElem::new(lcg.next_fe())).collect();
    let init_digest = suite.hashfn.hash_elem_slice(&init_elems);
    let initial_commit = *init_digest.as_words().first_chunk::<8>().unwrap();

    // --- prove loop: mirror of vendored prove::fri::fri_prove, keeping the
    // per-round evaluation buffers (asserted byte-identical to the real
    // fri_prove below). ---
    let mut iop = WriteIOP::<BabyBear>::new(suite.rng.as_ref());
    iop.commit(&init_digest);
    let mut cur = hal.copy_from_elem("coeffs", &coeffs_vec);
    let mut round_provers: Vec<MerkleTreeProver<_>> = Vec::new();
    let mut round_evals: Vec<Vec<BabyBearElem>> = Vec::new();
    let mut round_domains: Vec<usize> = Vec::new();
    while cur.size() / EXT_SIZE > FRI_MIN_DEGREE {
        let size = cur.size() / EXT_SIZE;
        let domain = size * INV_RATE;
        let evaluated = hal.alloc_elem("evaluated", domain * EXT_SIZE);
        hal.batch_expand_into_evaluate_ntt(&evaluated, &cur, EXT_SIZE, log2_ceil(INV_RATE));
        let merkle = MerkleTreeProver::new(
            &hal,
            &evaluated,
            domain / FRI_FOLD,
            FRI_FOLD * EXT_SIZE,
            QUERIES,
        );
        merkle.commit(&mut iop);
        let fold_mix = iop.random_ext_elem();
        let out_coeffs = hal.alloc_elem("out_coeffs", size / FRI_FOLD * EXT_SIZE);
        hal.fri_fold(&out_coeffs, &cur, &fold_mix);
        evaluated.view(|v| round_evals.push(v.to_vec()));
        round_domains.push(domain);
        round_provers.push(merkle);
        cur = out_coeffs;
    }
    let rounds = round_provers.len();
    let final_degree = cur.size() / EXT_SIZE;
    let final_domain = final_degree * INV_RATE;

    // Final coefficients into natural order, write + commit.
    let final_buf = hal.alloc_elem("final_coeffs", cur.size());
    hal.eltwise_copy_elem(&final_buf, &cur);
    hal.batch_bit_reverse(&final_buf, EXT_SIZE);
    let final_off = iop.proof.len();
    let mut final_planes: Vec<BabyBearElem> = Vec::new();
    final_buf.view(|v| final_planes.extend_from_slice(v));
    iop.write_field_elem_slice::<BabyBearElem>(&final_planes);
    let final_digest = suite.hashfn.hash_elem_slice(&final_planes);
    iop.commit(&final_digest);
    // Natural-order ext coefficients of the final polynomial.
    let final_ext: Vec<BabyBearExtElem> = (0..final_degree)
        .map(|i| {
            BabyBearExtElem::from_subelems(
                (0..EXT_SIZE).map(|j| final_planes[j * final_degree + i]),
            )
        })
        .collect();
    let gen = <BabyBearElem as RootsOfUnity>::ROU_FWD[log2_ceil(final_domain)];

    // Query phase, checkpointing (pos, goal) before every round.
    let orig_domain = degree * INV_RATE;
    let mut qck: Vec<Vec<(usize, [u32; 4])>> = Vec::new();
    for _ in 0..QUERIES {
        let mut pos = iop.random_bits(log2_ceil(orig_domain)) as usize;
        let mut chain: Vec<(usize, [u32; 4])> = Vec::new();
        for r in 0..rounds {
            chain.push((pos, eval_at(&round_evals[r], round_domains[r], pos)));
            let group = pos % (round_domains[r] / FRI_FOLD);
            round_provers[r].prove(&hal, &mut iop, group);
            pos = group;
        }
        // Final comparison state: the verifier's own last check.
        let x = BabyBearExtElem::from_subfield(&gen.pow(pos));
        chain.push((pos, canon_ext(&poly_eval(&final_ext, x))));
        qck.push(chain);
    }
    let proof = iop.proof.clone();

    // --- byte-identity: the untouched fri_prove writes the same stream ---
    {
        let mut iop2 = WriteIOP::<BabyBear>::new(suite.rng.as_ref());
        iop2.commit(&init_digest);
        let coeffs2 = hal.copy_from_elem("coeffs2", &coeffs_vec);
        risc0_zkp::prove::fri::fri_prove(&hal, &mut iop2, &coeffs2, |_iop, _pos| {});
        assert_eq!(
            iop2.proof, proof,
            "{name}: re-implemented prove loop diverges from risc0-zkp fri_prove"
        );
    }

    FriCase {
        degree,
        initial_commit,
        proof,
        qck,
        final_off,
    }
}

// ---------------------------------------------------------------------------
// Oracle replay through risc0-zkp's own Verifier::fri_verify
// ---------------------------------------------------------------------------

/// Replay a (possibly corrupted) stream through the crate's own
/// `fri_verify`. `inner` convention shared with the Scala spec: return the
/// recorded round-0 goal for a known position, ZERO for an unknown one
/// (positions shift when a corruption lands before a challenge draw).
/// `bad_goal`: if set, the q-th inner call returns goal + 1 (must reject).
/// Returns false on any Err, panic (1.2.6 panics where 3.0.4 rejects), or
/// leftover proof words.
fn oracle_fri_ok(case: &FriCase, proof: &[u32], bad_goal: Option<usize>) -> bool {
    let goal_map: BTreeMap<usize, BabyBearExtElem> = case
        .qck
        .iter()
        .map(|chain| {
            let (pos, g) = chain[0];
            (
                pos,
                BabyBearExtElem::from_subelems(g.iter().map(|&v| BabyBearElem::new(v))),
            )
        })
        .collect();
    catch_unwind(AssertUnwindSafe(|| {
        let suite = Poseidon2HashSuite::new_suite();
        let circuit = NullCircuit;
        let verifier = Verifier::new(&circuit, &suite);
        let mut iop = ReadIOP::<BabyBear>::new(proof, suite.rng.as_ref());
        iop.commit(&Digest::from(case.initial_commit));
        let mut call = 0usize;
        let res = verifier.fri_verify(&mut iop, case.degree, |_iop, pos| {
            let mut g = goal_map
                .get(&pos)
                .copied()
                .unwrap_or(BabyBearExtElem::ZERO);
            if bad_goal == Some(call) {
                g += BabyBearExtElem::ONE;
            }
            call += 1;
            Ok(g)
        });
        if res.is_err() {
            return false;
        }
        iop.verify_complete(); // asserts in 1.2.6 — caught as reject
        true
    }))
    .unwrap_or(false)
}

// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------

fn main() {
    let out = Path::new(OUT_DIR);
    fs::create_dir_all(out).expect("mkdir out");

    let mut s = String::from(
        "# FRI verify vectors. Oracle: risc0-zkp 1.2.6 prove::fri::fri_prove / Verifier::fri_verify\n\
         # (Poseidon2 suite; verify/fri.rs value-identical to 3.0.4, which the node links — see\n\
         # fri_kat.rs version note). Streams byte-asserted against the untouched fri_prove; every\n\
         # vector, positive AND negative, replayed through risc0-zkp's own fri_verify before emission.\n\
         # rou_fwd/rou_rev: risc0-core BabyBear ROU_FWD/ROU_REV per po2 0..=27, CANONICAL form.\n\
         # Per case: initial_commit = 8 RAW digest words mixed before the FRI stream begins;\n\
         # proof = full word stream (round Merkle tops, final poly, per-query branches);\n\
         # qck:<q>,<r> -> <pos>,<g0..g3> = query q's (position, canonical goal) BEFORE round r\n\
         # (r=0 rows double as the inner(pos) map; r=rounds is the final-poly comparison state).\n\
         # inner convention (both sides): known pos -> recorded r=0 goal; unknown pos -> 0.\n\
         # Negatives (oracle-confirmed rejects): badword:<word_idx>,<xor> | truncate:<words kept> |\n\
         # badgoal:<q> (inner call q returns goal+1). final_off:<w> = first final-poly word.\n",
    );

    let rou_fwd: Vec<u32> = <BabyBearElem as RootsOfUnity>::ROU_FWD
        .iter()
        .map(|&e| u32::from(e))
        .collect();
    let rou_rev: Vec<u32> = <BabyBearElem as RootsOfUnity>::ROU_REV
        .iter()
        .map(|&e| u32::from(e))
        .collect();
    assert_eq!(rou_fwd.len(), 28);
    assert_eq!(rou_rev.len(), 28);
    s.push_str(&format!("rou_fwd:{}\n", join_u32(&rou_fwd)));
    s.push_str(&format!("rou_rev:{}\n", join_u32(&rou_rev)));

    // Degrees crossing 0, 1, 2 and 3 fold rounds; po2=18 (3 rounds, final
    // degree 64) is the real succinct receipt's configuration.
    let cases = [
        ("deg256_r0", 256usize, 0xE1900045_0000000Au64),
        ("deg4096_r1", 4096, 0xE1900045_0000000B),
        ("deg65536_r2", 65536, 0xE1900045_0000000C),
        ("deg262144_r3", 262144, 0xE1900045_0000000D),
    ];

    for (name, degree, seed) in cases {
        let case = gen_case(name, degree, seed);
        let rounds = case.qck[0].len() - 1;
        println!(
            "{name}: degree {degree}, {rounds} rounds, {} proof words",
            case.proof.len()
        );

        assert!(
            oracle_fri_ok(&case, &case.proof, None),
            "{name}: positive vector failed oracle replay"
        );

        s.push_str(&format!("case:{name},{degree},{QUERIES}\n"));
        s.push_str(&format!("initial_commit:{}\n", join_u32(&case.initial_commit)));
        s.push_str(&format!("final_off:{}\n", case.final_off));
        s.push_str(&format!("proof:{}\n", join_u32(&case.proof)));
        for (q, chain) in case.qck.iter().enumerate() {
            for (r, (pos, g)) in chain.iter().enumerate() {
                s.push_str(&format!(
                    "qck:{q},{r} -> {pos},{}\n",
                    join_u32(g)
                ));
            }
        }

        // Negatives — every one oracle-confirmed as a reject before emission.
        let mut badwords: Vec<(usize, u32)> = vec![
            // First stream word: a round-root top digest word (or a final-poly
            // word for the 0-round case) — corrupts a committed digest.
            (0, 1),
            // Last stream word: inside the last query's branch data.
            (case.proof.len() - 1, 1),
            // First final-poly word pushed >= 2^31: the field-element read
            // itself must reject (word >= P).
            (case.final_off, 0x8000_0000),
        ];
        if rounds > 0 {
            // Flip a final-poly value: final digest changes, so the query
            // positions shift and the round checks mismatch.
            badwords.push((case.final_off, 1));
        }
        for (pos, xor) in badwords {
            let mut p = case.proof.clone();
            p[pos] ^= xor;
            assert!(
                !oracle_fri_ok(&case, &p, None),
                "{name}: badword vector unexpectedly verified (pos {pos})"
            );
            s.push_str(&format!("badword:{pos},{xor}\n"));
        }
        let trunc = case.proof.len() - 1;
        assert!(
            !oracle_fri_ok(&case, &case.proof[..trunc], None),
            "{name}: truncated vector unexpectedly verified"
        );
        s.push_str(&format!("truncate:{trunc}\n"));
        for q in [0, QUERIES - 1] {
            assert!(
                !oracle_fri_ok(&case, &case.proof, Some(q)),
                "{name}: badgoal vector unexpectedly verified (q {q})"
            );
            s.push_str(&format!("badgoal:{q}\n"));
        }
        s.push_str("endcase\n");
    }

    fs::write(out.join("fri_kat.tsv"), s).expect("write fri tsv");
    println!("wrote fri_kat.tsv (oracle-replayed, negatives oracle-confirmed)");
}
