//! KAT generator for the EIP-0045 verifyStark JVM `FriVerifier` (the FRI
//! low-degree-test phase of risc0-zkp's STARK verify).
//!
//! Every vector is produced by risc0-zkp 1.2.6 ITSELF (prover side:
//! `prove::fri::fri_prove` + `MerkleTreeProver` + `WriteIOP`; oracle side:
//! `Verifier::fri_verify` + `ReadIOP`) — never by the Scala code under
//! test. The crate-private prover/verifier internals are reached through
//! the vendored visibility-only patch in `vendor/risc0-zkp-1.2.6` (see
//! Cargo.toml `[patch.crates-io]`; grep "PATCHED").
//!
//! Sanity rules:
//!  - The proof stream of each case is generated by a re-implementation of
//!    `fri_prove`'s loop (needed to capture per-round evaluation buffers
//!    for checkpoints) and asserted BYTE-IDENTICAL to the stream written
//!    by risc0-zkp's own untouched `prove::fri::fri_prove` on the same
//!    inputs.
//!  - Every emitted vector — positive AND negative — is replayed through
//!    risc0-zkp's OWN `Verifier::fri_verify` before being written
//!    (assert!), mirroring merkle_iop_kat.rs.
//!
//! Determinism: no RNG — inputs derive from fixed LCG seeds so re-running
//! the generator reproduces byte-identical vectors.
//!
//! Version note: these vectors are generated with risc0-zkp 1.2.6 and are
//! byte-valid for 3.0.4 (the version the node's succinct verify path
//! links): `verify/fri.rs` differs between the two versions only in error
//! plumbing (1.2.6 panics / 3.0.4 `Err(VerificationError)`), iop-handle
//! threading, and the arithmetic of an internal `rounds_capacity`
//! allocation assert (`log2_ceil(d.div_ceil(16)).div_ceil(4)` in 1.2.6 vs
//! `log2_ceil(d.div_ceil(16).div_ceil(4))` in 3.0.4 — both bounds exceed
//! the actual round count for every reachable degree, and neither touches
//! the proof stream). `core/ntt.rs` and the FRI fold/query math are
//! value-identical. The Scala port follows the 3.0.4 rejection semantics.
//!
//! Wire-form notes (the raw/canonical Montgomery trap): digest words on
//! the wire are RAW Montgomery residues; field elements on the wire are
//! ALSO raw Montgomery residues (`write_field_elem_slice` emits the
//! internal repr). This file records field-element VALUES in canonical
//! form (`Elem::as_u32`) and digests in RAW form, matching the Scala API
//! boundary under test.
//!
//! Checkpoint semantics (`qck` rows): checkpoint `(q, r)` is the query's
//! `(pos, goal)` state immediately BEFORE fold round `r` processes it;
//! `r == rounds` is the state checked against the final polynomial. Goals
//! for `r < rounds` come from round `r`'s prover evaluation buffer (the
//! very data whose Merkle root is committed in the stream); the
//! `r == rounds` goal is the final polynomial evaluated with risc0-core's
//! own arithmetic at `ROU_FWD[log2(final_domain)]^pos` — exactly the
//! verifier's final comparison.

