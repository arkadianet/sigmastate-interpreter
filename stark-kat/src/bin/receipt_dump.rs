//! Oracle dump of the bincode-serialized `InnerReceipt` fixture for the
//! Scala receipt parser KATs (`sigma.stark.receipt.ReceiptParseSpec`).
//!
//! Deserializes `../core/jvm/src/test/resources/stark-kats/proof_inner.bin`
//! with the REAL `risc0_verifier` types (the same crate + tag the Rust Ergo
//! node's verifyStark spike links) and emits every field the Scala parser
//! must reproduce into `receipt_struct.tsv` — the Scala code under test
//! NEVER produces an expected value here (oracle-parity rule).
//!
//! Also emits reject vectors: truncation lengths and single-byte length-region
//! corruptions, each CONFIRMED to fail `bincode::deserialize` in Rust before
//! it is written, plus the observed trailing-byte policy of the oracle
//! (bincode 1.x legacy `deserialize` allows trailing bytes).
//!
//! Wire format (bincode 1.x legacy/default config), verified against the
//! actual fixture bytes by the offset arithmetic below (the sum of all
//! section sizes must equal the file length or this tool aborts):
//!   - little-endian, FIXED-width ints; enum variant index as u32
//!   - Vec<T>: u64 element count + elements; String: u64 byte len + UTF-8
//!   - Option<T>: single byte 0/1 (+ payload)
//!   - Digest: transparent newtype over [u32; 8] -> exactly 32 bytes, NO
//!     length prefix (fixed-size array)

use std::fmt::Write as _;
use std::fs;

use risc0_verifier::{
    receipt_claim::{MaybePruned, ReceiptClaim},
    InnerReceipt,
};

const KATS: &str = "../core/jvm/src/test/resources/stark-kats";

fn hex(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        let _ = write!(s, "{b:02x}");
    }
    s
}

fn digest_hex(d: &risc0_verifier::Digest) -> String {
    hex(d.as_bytes())
}

fn words_csv(ws: &[u32]) -> String {
    ws.iter().map(|w| w.to_string()).collect::<Vec<_>>().join(",")
}

fn main() {
    let path = format!("{KATS}/proof_inner.bin");
    let bytes = fs::read(&path).expect("read proof_inner.bin");

    let inner: InnerReceipt =
        bincode::deserialize(&bytes).expect("fixture must deserialize as InnerReceipt");
    let sr = match &inner {
        InnerReceipt::Succinct(sr) => sr,
        InnerReceipt::Composite(_) => panic!("fixture is expected to be the Succinct variant"),
    };

    let mut out = String::new();
    out.push_str("# Oracle dump of proof_inner.bin (risc0_verifier::InnerReceipt via bincode 1.x).\n");
    out.push_str("# Generated by stark-kat/src/bin/receipt_dump.rs — do not edit.\n");
    out.push_str("# key\tvalue  (u32 words as unsigned decimal; digests as hex of the 32 serialized bytes)\n");
    let mut kv = |k: &str, v: String| {
        out.push_str(k);
        out.push('\t');
        out.push_str(&v);
        out.push('\n');
    };

    kv("variant", "Succinct".into());
    kv("enum_tag", "1".into());

    // ----- succinct receipt fields -----
    let seal = &sr.seal;
    kv("seal_len", seal.len().to_string());
    kv("seal_first8", words_csv(&seal[..8]));
    kv("seal_last8", words_csv(&seal[seal.len() - 8..]));
    kv("control_id", digest_hex(&sr.control_id));

    match &sr.claim {
        MaybePruned::Pruned(d) => {
            kv("claim_variant", "Pruned".into());
            kv("claim_digest", digest_hex(d));
        }
        MaybePruned::Value(claim) => {
            kv("claim_variant", "Value".into());
            dump_claim(claim, &mut kv);
        }
    }

    kv("hashfn", sr.hashfn.clone());
    kv("verifier_parameters", digest_hex(&sr.verifier_parameters));

    let mp = &sr.control_inclusion_proof;
    kv("merkle_index", mp.index.to_string());
    kv("merkle_digests_len", mp.digests.len().to_string());
    for (i, d) in mp.digests.iter().enumerate() {
        kv(&format!("merkle_digest_{i}"), digest_hex(d));
    }

    // ----- byte offsets of major sections (verified against file length) -----
    let off_seal_len = 4u64; // after the u32 InnerReceipt variant tag
    let off_seal_words = off_seal_len + 8;
    let off_control_id = off_seal_words + 4 * seal.len() as u64;
    let off_claim = off_control_id + 32;
    let claim_size = bincode::serialized_size(&sr.claim).expect("size(claim)");
    let off_hashfn = off_claim + claim_size;
    let hashfn_size = 8 + sr.hashfn.len() as u64;
    let off_verifier_parameters = off_hashfn + hashfn_size;
    let off_merkle_proof = off_verifier_parameters + 32;
    let off_merkle_digests_len = off_merkle_proof + 4;
    let end = off_merkle_digests_len + 8 + 32 * mp.digests.len() as u64;
    assert_eq!(
        end,
        bytes.len() as u64,
        "offset arithmetic must account for every byte of the fixture"
    );
    kv("offset_enum_tag", "0".into());
    kv("offset_seal_len", off_seal_len.to_string());
    kv("offset_seal_words", off_seal_words.to_string());
    kv("offset_control_id", off_control_id.to_string());
    kv("offset_claim", off_claim.to_string());
    kv("offset_hashfn", off_hashfn.to_string());
    kv("offset_verifier_parameters", off_verifier_parameters.to_string());
    kv("offset_merkle_proof", off_merkle_proof.to_string());
    kv("offset_merkle_digests_len", off_merkle_digests_len.to_string());
    kv("total_len", bytes.len().to_string());

    // ----- oracle trailing-byte policy -----
    // bincode 1.x legacy `deserialize` allows trailing bytes; record the
    // actually observed behavior so the Scala parser can mirror it.
    let mut with_trailing = bytes.clone();
    with_trailing.push(0xAB);
    let trailing_ok = bincode::deserialize::<InnerReceipt>(&with_trailing).is_ok();
    kv("trailing_bytes_allowed", trailing_ok.to_string());

    // ----- reject vectors: truncations (each confirmed to fail in Rust) -----
    let truncations = [
        0usize,                       // empty input
        2,                            // inside the u32 enum tag
        8,                            // inside the u64 seal length
        1000,                         // inside the seal words
        off_hashfn as usize + 3,      // inside the u64 hashfn length
        bytes.len() - 1,              // one byte short of a full receipt
    ];
    for t in truncations {
        let err = bincode::deserialize::<InnerReceipt>(&bytes[..t]).is_err();
        assert!(err, "truncation to {t} bytes unexpectedly deserialized");
        kv("truncate_fails", t.to_string());
    }

    // ----- reject vectors: length-region corruptions (confirmed in Rust) -----
    // XOR the top byte of a u64 length prefix -> astronomically large length,
    // which must be rejected, not allocated.
    let corruptions = [
        (off_seal_len as usize + 7, 0x80u8),          // seal length high byte
        (off_hashfn as usize + 7, 0x80u8),            // hashfn length high byte
        (off_merkle_digests_len as usize + 7, 0x80u8) // merkle digests count high byte
    ];
    for (off, x) in corruptions {
        let mut c = bytes.clone();
        c[off] ^= x;
        let err = bincode::deserialize::<InnerReceipt>(&c).is_err();
        assert!(err, "corruption at {off} ^ {x:#04x} unexpectedly deserialized");
        kv("corrupt_fails", format!("{off},{x}"));
    }

    let out_path = format!("{KATS}/receipt_struct.tsv");
    fs::write(&out_path, out).expect("write receipt_struct.tsv");
    println!("wrote {out_path} (all reject vectors oracle-confirmed)");
}

fn dump_claim(claim: &ReceiptClaim, kv: &mut impl FnMut(&str, String)) {
    match &claim.pre {
        MaybePruned::Pruned(d) => {
            kv("claim_pre_variant", "Pruned".into());
            kv("claim_pre_digest", digest_hex(d));
        }
        MaybePruned::Value(ss) => {
            kv("claim_pre_variant", "Value".into());
            kv("claim_pre_pc", ss.pc.to_string());
            kv("claim_pre_merkle_root", digest_hex(&ss.merkle_root));
        }
    }
    match &claim.post {
        MaybePruned::Pruned(d) => {
            kv("claim_post_variant", "Pruned".into());
            kv("claim_post_digest", digest_hex(d));
        }
        MaybePruned::Value(ss) => {
            kv("claim_post_variant", "Value".into());
            kv("claim_post_pc", ss.pc.to_string());
            kv("claim_post_merkle_root", digest_hex(&ss.merkle_root));
        }
    }
    // ExitCode serializes as (sys, user) pair only through into_pair(); dump both
    // the variant name and the pair for unambiguous parity.
    let (sys, user) = claim.exit_code.into_pair();
    let name = match sys {
        0 => "Halted",
        1 => "Paused",
        2 => "SystemSplit",
        3 => "SessionLimit",
        _ => "Unknown",
    };
    kv("claim_exit_code", format!("{name},{user}"));
    match &claim.input {
        MaybePruned::Pruned(d) => {
            kv("claim_input_variant", "Pruned".into());
            kv("claim_input_digest", digest_hex(d));
        }
        MaybePruned::Value(opt) => {
            kv("claim_input_variant", "Value".into());
            kv("claim_input_some", opt.is_some().to_string());
        }
    }
    match &claim.output {
        MaybePruned::Pruned(d) => {
            kv("claim_output_variant", "Pruned".into());
            kv("claim_output_digest", digest_hex(d));
        }
        MaybePruned::Value(None) => {
            kv("claim_output_variant", "Value".into());
            kv("claim_output_some", "false".into());
        }
        MaybePruned::Value(Some(output)) => {
            kv("claim_output_variant", "Value".into());
            kv("claim_output_some", "true".into());
            match &output.journal {
                MaybePruned::Pruned(d) => {
                    kv("claim_output_journal_variant", "Pruned".into());
                    kv("claim_output_journal_digest", digest_hex(d));
                }
                MaybePruned::Value(j) => {
                    kv("claim_output_journal_variant", "Value".into());
                    kv("claim_output_journal", hex(j));
                }
            }
            match &output.assumptions {
                MaybePruned::Pruned(d) => {
                    kv("claim_output_assumptions_variant", "Pruned".into());
                    kv("claim_output_assumptions_digest", digest_hex(d));
                }
                MaybePruned::Value(list) => {
                    kv("claim_output_assumptions_variant", "Value".into());
                    kv("claim_output_assumptions_len", list.0.len().to_string());
                }
            }
        }
    }
}
